"""Print the exact comment bodies used in PR #1, for a given commit SHA.

Usage: python3 make_bodies.py <40-hex commit sha> > bodies.json

Each blob URL counts every character from "https://" through the "#L1-L3"
anchor. The fixture file names are padded so the URLs are exactly 103, 104,
149, 150, 151 and 152 characters long at any full commit SHA.
"""
import json
import sys

sha = sys.argv[1]
assert len(sha) == 40, "pass a full 40-character commit SHA"
base = f"https://github.com/Nerlant/review-link-repro/blob/{sha}/"
paths = {103: "a1.txt", 104: "a12.txt"}
for n in (149, 150, 151, 152):
    paths[n] = f"fixtures/url-{n}-chars-" + "x" * (n - 124) + ".txt"
U = {n: base + p + "#L1-L3" for n, p in paths.items()}
for n, u in U.items():
    assert len(u) == n, (n, len(u))

F = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"
bodies = {
    "c1": f"Case 1 (inline, `add_comment_to_pending_review`): one link, URL of 103 characters: [a1.txt]({U[103]}){F}",
    "c2": f"Case 2 (inline, `add_comment_to_pending_review`): one link, URL of 104 characters: [a12.txt]({U[104]}){F}",
    "c3": f"Case 3 (inline, `add_comment_to_pending_review`): one link, URL of 149 characters: [url-149]({U[149]}){F}",
    "c4": f"Case 4 (inline, `add_comment_to_pending_review`): one link, URL of 150 characters: [url-150]({U[150]}){F}",
    "c5": (
        "Case 5 (inline, multi-line, `add_comment_to_pending_review`): three links of 150, 151 and 152 "
        "characters in one body, in the sentence shapes of the original review: "
        f"first ([url-150]({U[150]})), then ([url-151]({U[151]})). Last ([url-152]({U[152]})), end.{F}"
    ),
    "review": f"Case 6 (review body, `pull_request_review_write` submit_pending): [url-149]({U[149]}) and [url-150]({U[150]}).{F}",
    "c7": f"Case 7 (PR conversation comment, `add_issue_comment`): [url-149]({U[149]}) and [url-150]({U[150]}).{F}",
}
json.dump({"paths": paths, "urls": U, "bodies": bodies}, sys.stdout, indent=1, ensure_ascii=False)
print()
